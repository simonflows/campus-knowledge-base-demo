export type ArticleChunk = {
  id: string;
  content: string;
};

export type ArticleSection = {
  id: string;
  heading: string;
  level: 2 | 3;
  chunks: ArticleChunk[];
};

export type ReadyArticle = {
  id: string;
  title: string;
  lead: string;
  sections: ArticleSection[];
  sourceCardIds: string[];
  sourceCardTitles: string[];
  universityId: string;
  projectTitle: string;
  topic: string;
  query: string;
  createdAt: string;
  updatedAt: string;
  diskSync?: DiskSyncInfo;
};

export type GeneratedArticleDraft = Omit<
  ReadyArticle,
  "id" | "createdAt" | "updatedAt" | "universityId"
> & {
  suggestedUniversityId: string | null;
  noData: boolean;
  noDataMessage: string | null;
  usedArticleIds: string[];
};

export type ArticleSourceSummary = {
  id: string;
  title: string;
  type: KnowledgeCard["type"];
  description: string;
};

export type FlatArticleChunk = {
  articleId: string;
  articleTitle: string;
  sectionId: string;
  sectionHeading: string;
  chunkId: string;
  content: string;
};

export function flattenArticleChunks(
  article: ReadyArticle
): FlatArticleChunk[] {
  return article.sections.flatMap((section) =>
    section.chunks.map((chunk) => ({
      articleId: article.id,
      articleTitle: article.title,
      sectionId: section.id,
      sectionHeading: section.heading,
      chunkId: chunk.id,
      content: chunk.content,
    }))
  );
}

export function countArticleChars(article: ReadyArticle): number {
  const bodyChars = article.sections.reduce(
    (total, section) =>
      total +
      section.chunks.reduce((sum, chunk) => sum + chunk.content.length, 0),
    0
  );

  return article.lead.length + bodyChars;
}

